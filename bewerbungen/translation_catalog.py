"""The catalog of the app's translations (#414, G10, docs/design/sprachen.md).

One JSON file per group of items in `sprachen/`. The German source text is the key, so German needs no entry and a
missing entry shows German: `{"Gespeichert.": {"fr": "Enregistré.", "en": "Saved."}}`. A text set of `seiten/texte.js`
is written as `"texte:<key>"` with its forms: `{"fr": {"sie": …, "du": …, "lehrstelle"?: …}, "en": {"sie": …,
"lehrstelle"?: …}}`; English has no du and falls back to Sie. Files merge; the same key twice is fine only with the
same translation.
"""
import dataclasses
import functools
import json
import pathlib
import types
from typing import Any, Mapping

CATALOG_DIR = pathlib.Path(__file__).resolve().parent / "sprachen"
LANGUAGES = ("fr", "en")
SET_PREFIX = "texte:"
# The order a set falls back in: an apprenticeship takes du, du takes Sie (English has no du).
FALLBACK = {"lehrstelle": ("lehrstelle", "du", "sie"), "du": ("du", "sie"), "sie": ("sie",)}


class CatalogError(Exception):
    """A catalog file the app cannot use; named with the file, for whoever edits the catalog. Not a ValueError, so a
    route never answers it as a wrong value of the person (400)."""


@dataclasses.dataclass(frozen=True)
class Catalog:
    entries: Mapping[str, Any]
    origins: Mapping[str, tuple[str, ...]]  # key -> the files that hold it

    def text(self, german: str, language: str) -> str | None:
        """The translation of a plain text, or None: the page then keeps the German."""
        entry = None if german.startswith(SET_PREFIX) else self.entries.get(german)
        found = entry.get(language) if isinstance(entry, Mapping) else None
        return found if isinstance(found, str) and found else None

    def form(self, key: str, language: str, form: str) -> str | None:
        """One form of a text set, with the fallback of FALLBACK, or None."""
        forms = _forms(self.entries.get(SET_PREFIX + key), language)
        found = next((forms[name] for name in FALLBACK.get(form, ()) if forms.get(name)), None)
        return found if isinstance(found, str) else None

    def for_page(self, language: str) -> dict:
        """What /uebersetzung.js hands the scripts of a page: plain texts and text sets of one language."""
        texts = {key: self.text(key, language) for key in self.entries if not key.startswith(SET_PREFIX)}
        sets = {key[len(SET_PREFIX):]: _forms(entry, language) for key, entry in self.entries.items()
                if key.startswith(SET_PREFIX)}
        return {"sprache": language, "texte": {key: value for key, value in texts.items() if value},
                "saetze": {key: value for key, value in sets.items() if value}}


def _forms(entry: Any, language: str) -> dict:
    forms = entry.get(language) if isinstance(entry, Mapping) else None
    return {name: value for name, value in forms.items() if isinstance(value, str)} if isinstance(forms, Mapping) else {}


def _read(path: pathlib.Path) -> dict:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError) as error:
        raise CatalogError(f"{path.name}: not readable as JSON ({error})") from error
    if not isinstance(data, dict):
        raise CatalogError(f"{path.name}: expected an object of German texts")
    return data


def load(folder: pathlib.Path) -> Catalog:
    """Every file of `folder` merged; a missing folder is an empty catalog."""
    files = sorted(folder.glob("*.json")) if folder.is_dir() else []
    pairs = [(key, value, path.name) for path in files for key, value in _read(path).items()]
    entries: dict[str, Any] = {}
    origins: dict[str, tuple[str, ...]] = {}
    for key, value, name in pairs:
        if key in entries and entries[key] != value:
            raise CatalogError(f"{key!r}: {origins[key][0]} and {name} translate it differently")
        entries[key] = value
        origins[key] = (*origins.get(key, ()), name)
    return Catalog(types.MappingProxyType(entries), types.MappingProxyType(origins))


def _stamp(folder: pathlib.Path) -> tuple:
    if not folder.is_dir():
        return ()
    return tuple((path.name, path.stat().st_mtime_ns, path.stat().st_size) for path in sorted(folder.glob("*.json")))


@functools.lru_cache(maxsize=4)
def _cached(folder: pathlib.Path, stamp: tuple) -> Catalog:
    return load(folder)


def current() -> Catalog:
    """The catalog of the app, read again only when a file changed."""
    return _cached(CATALOG_DIR, _stamp(CATALOG_DIR))


def script(language: str) -> str:
    """/uebersetzung.js for one language: sets `Uebersetzung` for texte.js."""
    data = json.dumps(current().for_page(language), ensure_ascii=False)
    return ('"use strict";\n// Generated by translation_catalog.py from bewerbungen/sprachen/ (#414); never edit it.\n'
            f'(function (global) {{ global.Uebersetzung = Object.freeze({data}); }})'
            '(typeof window !== "undefined" ? window : globalThis);\n')
